---------------------------------------------------
-- CREATE TABLES
---------------------------------------------------

CREATE TABLE DEPT
(
    DCODE CHAR(4) PRIMARY KEY,
    DNAME VARCHAR2(30)
);

CREATE TABLE EMP
(
    ECODE CHAR(5) PRIMARY KEY,
    ENAME VARCHAR2(30),
    DCODE CHAR(4),
    GRADE CHAR(1),
    BASIC NUMBER(8,2),
    JN_DT DATE,
    CONSTRAINT FK_EMP_DEPT
    FOREIGN KEY (DCODE)
    REFERENCES DEPT(DCODE)
);

CREATE TABLE ORDERMAST
(
    ORDER_NO CHAR(5) PRIMARY KEY,
    ORDER_DT DATE
);

CREATE TABLE ORDERDETAILS
(
    ORDER_NO CHAR(5),
    ITEM_NO CHAR(5),
    QTY NUMBER,
    CONSTRAINT PK_ORDERDETAILS
    PRIMARY KEY(ORDER_NO,ITEM_NO)
);

CREATE TABLE DELIVERYMAST
(
    DELV_NO CHAR(5) PRIMARY KEY,
    ORDER_NO CHAR(5),
    DELV_DT DATE
);

CREATE TABLE DELIVERY_DETAILS
(
    DELV_NO CHAR(5),
    ITEM_NO CHAR(5),
    QTY NUMBER,
    CONSTRAINT PK_DELIVERY_DETAILS
    PRIMARY KEY(DELV_NO,ITEM_NO)
);

CREATE TABLE LEAVE_TAB
(
    EMP_NO CHAR(5),
    MONTH_NAME VARCHAR2(10),
    NO_OF_DAYS NUMBER
);

